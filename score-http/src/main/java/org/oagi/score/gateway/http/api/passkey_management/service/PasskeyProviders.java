package org.oagi.score.gateway.http.api.passkey_management.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.webauthn4j.converter.AttestationObjectConverter;
import com.webauthn4j.converter.util.ObjectConverter;
import com.webauthn4j.data.attestation.AttestationObject;
import com.webauthn4j.data.attestation.authenticator.AttestedCredentialData;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.ClassPathResource;

import java.io.IOException;
import java.io.InputStream;
import java.util.HashMap;
import java.util.Locale;
import java.util.Map;
import java.util.UUID;
import java.util.regex.Pattern;

/**
 * Names the passkey manager or authenticator that holds a passkey, from the authenticator ID (AAGUID) in its stored
 * registration data. For display only; the AAGUID is not signed, so nothing relies on it.
 * <p>
 * The names and icons are read from {@code aaguid.json} on the classpath (each distinct icon is stored once, in "icons", and providers refer to their light and dark icon by key), which is generated by
 * {@code scripts/update-passkey-providers.py} from the community list
 * <a href="https://github.com/passkeydeveloper/passkey-authenticator-aaguids">passkey-authenticator-aaguids</a>; run
 * it from time to time. An authenticator that is not listed, or that reports all zeros, has no name.
 */
final class PasskeyProviders {

    /** A provider's display name and its light and dark icons as base64 SVG data URIs (null if it has none). */
    record Provider(String name, String iconLight, String iconDark) {
    }

    /** Shown for a passkey whose provider is not in the list; it has no icon of its own, so the page's default one is used. */
    static final Provider UNKNOWN = new Provider("Unknown", null, null);

    private static final Logger logger = LoggerFactory.getLogger(PasskeyProviders.class);

    /** Only an inline base64 SVG is passed on to the page, which shows it in an img tag. */
    private static final Pattern ICON = Pattern.compile("^data:image/svg\\+xml;base64,[A-Za-z0-9+/=]+$");

    private static final String RESOURCE = "aaguid.json";

    private static final AttestationObjectConverter CONVERTER = new AttestationObjectConverter(new ObjectConverter());

    private static final Map<UUID, Provider> PROVIDERS = load(new ClassPathResource(RESOURCE));

    private PasskeyProviders() {
    }

    static Map<UUID, Provider> load(ClassPathResource resource) {
        Map<UUID, Provider> providers = new HashMap<>();
        try (InputStream in = resource.getInputStream()) {
            JsonNode document = new ObjectMapper().readTree(in);
            JsonNode icons = document.path("icons");
            JsonNode entries = document.path("providers");
            entries.fields().forEachRemaining(entry -> {
                String name = entry.getValue().path("name").asText("");
                String light = icons.path(entry.getValue().path("icon_light").asText("")).asText("");
                String dark = icons.path(entry.getValue().path("icon_dark").asText("")).asText("");
                if (!name.isBlank()) {
                    providers.put(UUID.fromString(entry.getKey().toLowerCase(Locale.ROOT)),
                            new Provider(name, ICON.matcher(light).matches() ? light : null,
                                    ICON.matcher(dark).matches() ? dark : null));
                }
            });
        } catch (IOException | RuntimeException e) {
            // Names are a nicety: the passkey list must work without them.
            logger.warn("Passkey provider names are not available: cannot read {}", RESOURCE, e);
            return Map.of();
        }
        return Map.copyOf(providers);
    }

    /**
     * The provider of the passkey, or {@link #UNKNOWN} when its AAGUID is not in the list (including all zeros) or the
     * registration data is missing or unreadable.
     */
    static Provider find(byte[] attestationObject) {
        if (attestationObject == null || attestationObject.length == 0) {
            return UNKNOWN;
        }
        try {
            AttestationObject parsed = CONVERTER.convert(attestationObject);
            AttestedCredentialData data = parsed.getAuthenticatorData().getAttestedCredentialData();
            Provider provider = (data == null) ? null : PROVIDERS.get(data.getAaguid().getValue());
            return (provider != null) ? provider : UNKNOWN;
        } catch (RuntimeException e) {
            return UNKNOWN;
        }
    }

}
