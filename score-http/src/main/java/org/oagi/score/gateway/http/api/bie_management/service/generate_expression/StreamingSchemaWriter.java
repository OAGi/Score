package org.oagi.score.gateway.http.api.bie_management.service.generate_expression;

import org.jdom2.Attribute;
import org.jdom2.Document;
import org.jdom2.Element;
import org.jdom2.Namespace;
import org.jdom2.output.Format;
import org.jdom2.output.XMLOutputter;
import org.jdom2.output.support.AbstractXMLOutputProcessor;
import org.jdom2.output.support.FormatStack;
import org.jdom2.util.NamespaceStack;

import java.io.*;
import java.nio.channels.Channels;
import java.nio.channels.FileChannel;
import java.nio.charset.StandardCharsets;
import java.nio.file.StandardOpenOption;
import java.util.*;

/**
 * Writes the {@code xsd:schema} that a generator builds as a JDOM tree without keeping the whole tree.
 * <p>
 * <b>The purpose of this class is to write, byte for byte, the file that {@link XMLOutputter} writes for the whole
 * tree</b> (the pretty format with a tab indent), while the tree is never whole in memory. That contract, not this
 * implementation, is what callers rely on: it is checked by {@code StreamingSchemaWriterTest}, which compares random
 * trees of the shape the generator builds with the output of {@link XMLOutputter}. (When the XML generator moved to
 * this class every BIE and BIE package of a database was generated by the DOM-based generator and by this writer and
 * the files were the same, byte for byte, also in Inverse Mode.) The implementation leans on the protected steps of JDOM's own output processor
 * so that the formatting is JDOM's and is not imitated, and it can be replaced by another one (a StAX writer, say)
 * as long as those tests still pass.
 * <p>
 * A generator builds the elements that nest to the depth of the BIE (the "spine": the top-level element, its
 * {@code complexType}, the compositor, the element of each ASBIE, ...) and hangs a finished child on its parent.
 * This class takes over once a child is finished: the generator tells it which elements are in progress
 * ({@link #enter}/{@link #exit}) and when the finished children of the innermost in-progress element can go
 * ({@link #flushChildren()}). The start tags of the in-progress elements are written the first time one of their
 * descendants has to be written, the finished children are written through JDOM's own pretty-printer at the
 * indentation and namespace scope they would have in the whole tree, and are then detached. So the output is the
 * one {@link XMLOutputter} makes of the whole tree, byte for byte, while only the spine and the children of the
 * element in progress are in memory.
 * <p>
 * The body (what follows the {@code xsd:include}/{@code xsd:import} directives) is written to a spill file because
 * the directives and the namespace declarations of the schema element are known only when the generation is over.
 * The global components (code lists, ...) the generator hangs directly on the schema element stay in memory, so that
 * they can still be detached from the schema (the common files of a request take them away).
 * {@link #assemble(File)} writes the file and can be called again after the schema element changes.
 */
final class StreamingSchemaWriter {

    /**
     * The names of the two children of a probe schema element, which is written by {@link XMLOutputter} to learn the
     * text that it puts before the first child, between two children and after the last child of the schema element
     * (see {@link #frameTexts()}). They must not be the name of an element that a schema has.
     */
    private static final String PROBE_FIRST_CHILD = "byteParityProbeFirstChild";
    private static final String PROBE_SECOND_CHILD = "byteParityProbeSecondChild";

    /**
     * Gives the protected printing steps of JDOM to this class, so that a start tag and an end tag can be written
     * apart from each other with the same stack of formats and namespaces as {@code printElement} has.
     */
    private static final class Processor extends AbstractXMLOutputProcessor {

        void startTag(Writer out, FormatStack fstack, NamespaceStack nstack, Element element) throws IOException {
            nstack.push(element);
            write(out, "<");
            write(out, element.getQualifiedName());
            for (Namespace namespace : nstack.addedForward()) {
                printNamespace(out, fstack, namespace);
            }
            if (element.hasAttributes()) {
                for (Attribute attribute : element.getAttributes()) {
                    printAttribute(out, fstack, attribute);
                }
            }
            fstack.push();
            write(out, ">");
        }

        void endTag(Writer out, FormatStack fstack, NamespaceStack nstack, Element element) throws IOException {
            textRaw(out, fstack.getPadLast());
            write(out, "</");
            write(out, element.getQualifiedName());
            write(out, ">");
            fstack.pop();
            nstack.pop();
        }

        void child(Writer out, FormatStack fstack, NamespaceStack nstack, Element child) throws IOException {
            textRaw(out, fstack.getPadBetween());
            printElement(out, fstack, nstack, child);
        }

        void pad(Writer out, FormatStack fstack) throws IOException {
            textRaw(out, fstack.getPadBetween());
        }

        void bare(Writer out, FormatStack fstack, NamespaceStack nstack, Element element) throws IOException {
            printElement(out, fstack, nstack, element);
        }
    }

    private static final class Frame {
        final Element element;
        boolean started;

        Frame(Element element) {
            this.element = element;
        }
    }

    /**
     * A part of the body, in the order of the file.
     */
    private sealed interface Part permits Spilled, Declared {
    }

    private record Spilled(long offset, long length) implements Part {
    }

    private record Declared(Element element) implements Part {
    }

    private final Format format;
    private final Element schemaNode;
    private final Processor processor = new Processor();
    private final FormatStack fstack;
    private final NamespaceStack nstack = new NamespaceStack();
    private final Deque<Frame> frames = new ArrayDeque<>();
    private final List<Part> parts = new ArrayList<>();
    private final Set<Element> registered = Collections.newSetFromMap(new IdentityHashMap<>());

    private final File spillFile;
    private final CountingOutputStream spillBytes;
    private final Writer spill;
    private long chunkStart = -1;
    private boolean disposed;

    StreamingSchemaWriter(Element schemaNode, Format format) throws IOException {
        this.schemaNode = schemaNode;
        this.format = format;
        this.fstack = new FormatStack(format);
        // the body is written as the content of the schema element
        this.fstack.push();
        this.nstack.push(schemaNode);
        this.spillFile = File.createTempFile("bie-schema-", ".spill");
        this.spillBytes = new CountingOutputStream(new FileOutputStream(spillFile));
        this.spill = new BufferedWriter(new OutputStreamWriter(spillBytes, StandardCharsets.UTF_8), 1 << 16);
    }

    /**
     * Marks the element, a child of the innermost in-progress element (or of the schema element), as in progress.
     */
    void enter(Element element) {
        frames.push(new Frame(element));
    }

    /**
     * Whether the element in progress has written its start tag, which means that it has content.
     */
    boolean isStarted(Element element) {
        return frames.peek() != null && frames.peek().element == element && frames.peek().started;
    }

    /**
     * Writes the children the innermost in-progress element has now, which are all finished, and detaches them.
     */
    void flushChildren() {
        Frame top = frames.peek();
        if (top == null) {
            return;
        }
        if (top.element.getContentSize() == 0) {
            return;
        }
        try {
            startFrames(null);
            for (Element child : new ArrayList<>(top.element.getChildren())) {
                processor.child(spill, fstack, nstack, child);
                child.detach();
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /**
     * Finishes the innermost in-progress element, which must be the given one: writes what it still has and its end
     * tag if its start tag was written, or writes it whole as a finished child of the element in progress around it.
     */
    void exit(Element element) {
        Frame frame = frames.pop();
        if (frame.element != element) {
            throw new IllegalStateException("The element in progress is not " + element.getName());
        }
        try {
            if (frame.started) {
                for (Element child : new ArrayList<>(element.getChildren())) {
                    processor.child(spill, fstack, nstack, child);
                    child.detach();
                }
                processor.endTag(spill, fstack, nstack, element);
                if (frames.isEmpty()) {
                    closeChunk(element);
                }
                element.detach();
            } else {
                startFrames(element);
                if (frames.isEmpty()) {
                    openChunk();
                    processor.bare(spill, fstack, nstack, element);
                    closeChunk(element);
                } else {
                    processor.child(spill, fstack, nstack, element);
                }
                element.detach();
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /**
     * Writes a finished child of the schema element, or of the element in progress.
     */
    void emit(Element finished) {
        enter(finished);
        exit(finished);
    }

    /**
     * Drops the innermost in-progress element, which must be the given one and must have written nothing.
     */
    void discard(Element element) {
        Frame frame = frames.pop();
        if (frame.element != element || frame.started) {
            throw new IllegalStateException("The element in progress cannot be discarded: " + element.getName());
        }
        element.detach();
    }

    /**
     * Writes the start tags the in-progress elements have not written yet, from the outermost, each followed by the
     * children that precede the next in-progress element (for the innermost, the children that precede the
     * {@code before} element).
     */
    private void startFrames(Element before) throws IOException {
        List<Frame> outerToInner = new ArrayList<>(frames);
        Collections.reverse(outerToInner);
        for (int i = 0; i < outerToInner.size(); i++) {
            Frame frame = outerToInner.get(i);
            if (frame.started) {
                continue;
            }
            if (i == 0) {
                openChunk();
            } else {
                processor.pad(spill, fstack);
            }
            processor.startTag(spill, fstack, nstack, frame.element);
            frame.started = true;

            Element stop = (i + 1 < outerToInner.size()) ? outerToInner.get(i + 1).element : before;
            if (stop != null) {
                for (Element child : new ArrayList<>(frame.element.getChildren())) {
                    if (child == stop) {
                        break;
                    }
                    processor.child(spill, fstack, nstack, child);
                    child.detach();
                }
            }
        }
    }

    private void openChunk() throws IOException {
        spill.flush();
        chunkStart = spillBytes.count();
    }

    /**
     * Records the chunk that was written for the element, a child of the schema element, in the order of the body:
     * the global components the generator hung on the schema element around it go before or after it as they are.
     */
    private void closeChunk(Element element) throws IOException {
        spill.flush();
        long end = spillBytes.count();
        for (Element child : new ArrayList<>(schemaNode.getChildren())) {
            if (child == element) {
                parts.add(new Spilled(chunkStart, end - chunkStart));
            } else {
                registerDeclared(child);
            }
        }
        chunkStart = -1;
    }

    private void registerDeclared(Element child) {
        if (isDirective(child)) {
            return;
        }
        if (registered.add(child)) {
            parts.add(new Declared(child));
        }
    }

    private static boolean isDirective(Element element) {
        return "include".equals(element.getName()) || "import".equals(element.getName());
    }

    /**
     * Writes the schema file: the schema element with its directives and the body, in the order of a whole tree.
     * It can be called again after the schema element changed (a directive was added, a global component was
     * detached), as long as the writer is not disposed.
     */
    void assemble(File target) throws IOException {
        if (disposed) {
            throw new IllegalStateException("The schema is disposed");
        }
        if (!frames.isEmpty()) {
            throw new IllegalStateException("An element is still in progress: " + frames.peek().element.getName());
        }
        spill.flush();
        for (Element child : new ArrayList<>(schemaNode.getChildren())) {
            registerDeclared(child);
        }

        FormatStack outStack = new FormatStack(format);
        outStack.push();
        NamespaceStack outNamespaces = new NamespaceStack();
        outNamespaces.push(schemaNode);

        List<Object> items = new ArrayList<>();
        for (Element child : schemaNode.getChildren()) {
            if (isDirective(child)) {
                items.add(child);
            }
        }
        for (Part part : parts) {
            if (part instanceof Declared declared) {
                if (declared.element().getParent() != null) {
                    items.add(declared.element());
                }
            } else {
                items.add(part);
            }
        }

        try (OutputStream out = new BufferedOutputStream(new FileOutputStream(target), 1 << 16);
             FileChannel spillChannel = FileChannel.open(spillFile.toPath(), StandardOpenOption.READ)) {
            Writer writer = new OutputStreamWriter(out, StandardCharsets.UTF_8);
            if (items.isEmpty()) {
                writer.write(emptySchemaText());
                writer.flush();
                return;
            }
            String[] frame = frameTexts();
            writer.write(frame[0]);
            boolean first = true;
            for (Object item : items) {
                if (!first) {
                    writer.write(frame[1]);
                }
                first = false;
                if (item instanceof Spilled spilled) {
                    writer.flush();
                    long position = spilled.offset();
                    long remaining = spilled.length();
                    var target0 = Channels.newChannel(out);
                    while (remaining > 0) {
                        long transferred = spillChannel.transferTo(position, remaining, target0);
                        position += transferred;
                        remaining -= transferred;
                    }
                } else {
                    processor.bare(writer, outStack, outNamespaces, (Element) item);
                }
            }
            writer.write(frame[2]);
            writer.flush();
        }
    }

    /**
     * The text before the first child, between two children and after the last child of the schema element, so that
     * the XML declaration, the line breaks and the indentation are the ones of {@link XMLOutputter} and are not
     * written by hand here. It writes a probe document, the schema element (with its attributes and namespaces) with
     * two empty children, and cuts the output at the children:
     * <pre>
     *   [before]&lt;xsd:byteParityProbeFirstChild /&gt;[between]&lt;xsd:byteParityProbeSecondChild /&gt;[after]
     * </pre>
     */
    private String[] frameTexts() {
        Element shell = shell();
        shell.addContent(new Element(PROBE_FIRST_CHILD, schemaNode.getNamespace()));
        shell.addContent(new Element(PROBE_SECOND_CHILD, schemaNode.getNamespace()));
        String text = new XMLOutputter(format).outputString(new Document(shell));
        String prefix = schemaNode.getNamespace().getPrefix();
        String qualifiedPrefix = prefix.isEmpty() ? "" : prefix + ":";
        String firstChild = "<" + qualifiedPrefix + PROBE_FIRST_CHILD + " />";
        String secondChild = "<" + qualifiedPrefix + PROBE_SECOND_CHILD + " />";
        int first = text.indexOf(firstChild);
        int second = text.indexOf(secondChild);
        if (first < 0 || second < 0) {
            throw new IllegalStateException("XMLOutputter does not write an empty element as expected: " + text);
        }
        return new String[]{
                text.substring(0, first),
                text.substring(first + firstChild.length(), second),
                text.substring(second + secondChild.length())
        };
    }

    private String emptySchemaText() {
        return new XMLOutputter(format).outputString(new Document(shell()));
    }

    private Element shell() {
        Element shell = new Element(schemaNode.getName(), schemaNode.getNamespace());
        for (Namespace namespace : schemaNode.getAdditionalNamespaces()) {
            shell.addNamespaceDeclaration(namespace);
        }
        for (Attribute attribute : schemaNode.getAttributes()) {
            shell.setAttribute(attribute.clone());
        }
        return shell;
    }

    /**
     * Deletes the spill file. The writer cannot assemble the schema afterwards.
     */
    void dispose() {
        if (disposed) {
            return;
        }
        disposed = true;
        try {
            spill.close();
        } catch (IOException ignored) {
            // the file is deleted anyway
        }
        spillFile.delete();
    }

    private static final class CountingOutputStream extends FilterOutputStream {
        private long count;

        CountingOutputStream(OutputStream out) {
            super(out);
        }

        long count() {
            return count;
        }

        @Override
        public void write(int b) throws IOException {
            out.write(b);
            count++;
        }

        @Override
        public void write(byte[] b, int off, int len) throws IOException {
            out.write(b, off, len);
            count += len;
        }
    }
}
