/**
 * Time and memory of one XML generation, in a JVM of its own so that the numbers do not mix with the ones of another
 * run. Opt-in:
 * <pre>
 *   mvn test -Dtest=BieXmlStreamBenchmark \
 *       "-DargLine=-Xmx2g -Dscore.xmlbench=true -Dscore.xmlbench.bie=3 [-Dscore.xmlbench.inverse=true]"
 * </pre>
 * It prints one {@code XMLBENCH} line: the time, the size and the SHA-256 of the output (the options have no random
 * id, so the SHA-256 is the same from one run to another and tells whether a change altered the output), and the heap that is in use after the collections of the
 * run, whose maximum is the live set of the generation (peak = the garbage the collector had not yet reclaimed).
 */
@EnabledIfSystemProperty(named = "score.xmlbench", matches = "true")
@SpringBootTest(properties = {"spring.profiles.active=dev", "logging.level.root=WARN", "logging.level.org=WARN"})
class BieXmlStreamBenchmark {

    @Autowired
    private DSLContext dsl;
    @org.springframework.beans.factory.annotation.Value("${spring.datasource.url}")
    private String datasourceUrl;
    @Autowired
    private RepositoryFactory repositoryFactory;
    @Autowired
    private BieGenerateService bieGenerateService;

    @Test
    void generate() throws Exception {
        String bieProperty = System.getProperty("score.xmlbench.bie");
        if (bieProperty == null) {
            throw new IllegalArgumentException("-Dscore.xmlbench.bie=<top_level_asbiep_id> is required");
        }
        long bie = Long.parseLong(bieProperty.trim());
        boolean inverse = Boolean.getBoolean("score.xmlbench.inverse");

        BieGenerateService service = bieGenerateService;

        var record = dsl.fetchOne("select u.app_user_id, u.login_id, u.is_developer from top_level_asbiep t"
                + " join app_user u on u.app_user_id = t.owner_user_id where t.top_level_asbiep_id = " + bie);
        if (record == null) {
            // a BIE whose owner is not in the database is generated by a developer
            record = dsl.fetchOne("select app_user_id, login_id, is_developer from app_user where is_developer = 1 order by 1 limit 1");
        }
        ScoreUser owner = new ScoreUser(new UserId(record.get(0, ULong.class).toBigInteger()), record.get(1, String.class),
                record.get(1, String.class), null, false,
                record.get(2, Integer.class) == 1 ? List.of(ScoreRole.DEVELOPER) : List.of(ScoreRole.END_USER));
        TopLevelAsbiepSummaryRecord summary = repositoryFactory.topLevelAsbiepQueryRepository(owner)
                .getTopLevelAsbiepSummary(new TopLevelAsbiepId(BigInteger.valueOf(bie)));
        if (summary == null) {
            throw new IllegalArgumentException("There is no BIE of top_level_asbiep_id " + bie + " in " + datasourceUrl
                    + " (a BIE whose owner is not in app_user cannot be loaded either)");
        }
        if (inverse) {
            summary = withInverseMode(summary);
        }

        GenerateExpressionOption option = new GenerateExpressionOption();
        option.setExpressionOption("XML");
        option.setPackageOption("ALL");
        option.setBieDefinition(true);
        option.setBieCctsMetaData(true);
        option.setBusinessContext(true);
        option.setIncludeCctsDefinitionTag(true);
        option.setBieOagiScoreMetaData(true);
        option.setBasedCcMetaData(true);

        AtomicLong maxAfterGc = new AtomicLong();
        AtomicLong gcCount = new AtomicLong();
        for (GarbageCollectorMXBean gc : ManagementFactory.getGarbageCollectorMXBeans()) {
            ((NotificationEmitter) gc).addNotificationListener((notification, handback) -> {
                if (GarbageCollectionNotificationInfo.GARBAGE_COLLECTION_NOTIFICATION.equals(notification.getType())) {
                    var info = GarbageCollectionNotificationInfo.from((CompositeData) notification.getUserData());
                    // the heap pools only (Eden, Survivor, Old Gen), not Metaspace or the code cache
                    long used = info.getGcInfo().getMemoryUsageAfterGc().entrySet().stream()
                            .filter(e -> e.getKey().contains("Eden") || e.getKey().contains("Survivor")
                                    || e.getKey().contains("Old") || e.getKey().contains("Tenured"))
                            .mapToLong(e -> e.getValue().getUsed()).sum();
                    maxAfterGc.accumulateAndGet(used, Math::max);
                    gcCount.incrementAndGet();
                }
            }, null, null);
        }
        System.gc();
        long baseline = ManagementFactory.getMemoryMXBean().getHeapMemoryUsage().getUsed();
        maxAfterGc.set(0);

        long start = System.nanoTime();
        String outcome;
        long size = 0;
        String sha = "-";
        try {
            File file = service.generateSchema(owner, List.of(summary), option);
            long millis = (System.nanoTime() - start) / 1_000_000;
            size = file.length();
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            try (InputStream in = Files.newInputStream(file.toPath())) {
                byte[] buffer = new byte[1 << 16];
                for (int n; (n = in.read(buffer)) > 0; ) {
                    digest.update(buffer, 0, n);
                }
            }
            sha = java.util.HexFormat.of().formatHex(digest.digest());
            file.delete();
            outcome = "ok ms=" + millis;
        } catch (Throwable e) {
            outcome = "FAILED(" + e.getClass().getSimpleName() + ") ms=" + (System.nanoTime() - start) / 1_000_000;
        }
        System.out.println("XMLBENCH bie=" + bie + " inverse=" + inverse
                + " " + outcome + " outputBytes=" + size + " sha256=" + sha
                + " baselineMB=" + baseline / (1 << 20) + " maxLiveAfterGcMB=" + maxAfterGc.get() / (1 << 20)
                + " gcs=" + gcCount.get() + " xmxMB=" + Runtime.getRuntime().maxMemory() / (1 << 20));
    }

    /**
     * The record with {@code inverseMode} set, whatever the other components are (a record has no "with"; the
     * canonical constructor is called with the components of the record, so that a new component does not break this).
     */
    private static TopLevelAsbiepSummaryRecord withInverseMode(TopLevelAsbiepSummaryRecord summary) throws Exception {
        var components = TopLevelAsbiepSummaryRecord.class.getRecordComponents();
        Class<?>[] types = new Class<?>[components.length];
        Object[] values = new Object[components.length];
        for (int i = 0; i < components.length; i++) {
            types[i] = components[i].getType();
            values[i] = components[i].getName().equals("inverseMode") ? Boolean.TRUE : components[i].getAccessor().invoke(summary);
        }
        return TopLevelAsbiepSummaryRecord.class.getDeclaredConstructor(types).newInstance(values);
    }
}
